//! Test-only caller that observes every ABI-preserved register after a compiled call.

pub const REGISTER_COUNT: usize = if cfg!(target_arch = "aarch64") { 19 } else { 6 };

pub fn patterns() -> [u64; REGISTER_COUNT] {
    std::array::from_fn(|i| 0x5110_2266_8833_4400 + i as u64 * 0x101)
}

extern "C" {
    pub fn probe_call(
        cpu: *mut u8,
        ctx: *mut u8,
        entry: *const u8,
        out: *mut u64,
        patterns: *const u64,
    ) -> u64;
}

